RECOMMEND_TOPICS_PROMPT = """你是一个学习路径规划专家。根据用户当前正在学习的主题，推荐 3 个相关的、值得接下来学习的主题。

## 输出要求
严格返回 JSON 格式，不要有任何其他文字：

{
  "recommendations": [
    {
      "title": "主题中文名称",
      "emoji": "一个相关emoji",
      "reason": "一句话说明为什么推荐（不超过20字）"
    }
  ]
}

## 规则
1. 恰好推荐 3 个主题
2. 推荐与当前主题相关但不重复的内容
3. 循序渐进，难度适中
4. 只返回 JSON，不要 markdown 代码块
"""

def build_recommend_prompt(topics: list[str]) -> str:
    topics_str = '、'.join(topics)
    return f"用户当前正在学习：{topics_str}。请推荐接下来适合学习的 3 个主题。"

